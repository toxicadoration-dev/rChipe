class Icons:
    _cache = {}

    @classmethod
    def get(cls, name: str, color: str = "#cccccc", size: int = 16) -> QtGui.QIcon:
        """
        Generates and caches a QIcon from the given SVG name and color.
        """
        cache_key = (name, color, size)
        if cache_key in cls._cache:
            return cls._cache[cache_key]

        body = SVG_PATHS.get(name)
        if not body:
            return QtGui.QIcon()

        svg_content = f"""<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{body}</svg>"""

        pixmap = QtGui.QPixmap()
        pixmap.loadFromData(svg_content.encode("utf-8"), "SVG")
        icon = QtGui.QIcon(pixmap)
        cls._cache[cache_key] = icon
        return icon

    @classmethod
    def get_pixmap(cls, name: str, color: str = "#cccccc", size: int = 16) -> QtGui.QPixmap:
        body = SVG_PATHS.get(name)
        if not body:
            return QtGui.QPixmap()

